class HostClock final : public IClock {
public:
    [[nodiscard]] std::uint64_t now_us() const noexcept override {
        return static_cast<std::uint64_t>(std::chrono::duration_cast<std::chrono::microseconds>(
            std::chrono::steady_clock::now().time_since_epoch()).count());
    }
    void sleep_us(std::uint32_t value) noexcept override {
        std::this_thread::sleep_for(std::chrono::microseconds(value));
    }
};

// Fictional, deterministic protocol model. This is a host-side development
// fixture, not a model of any commercial device or undocumented service mode.
class DemoTransport final : public ITransport {
public:
    bool begin() noexcept override { started_ = true; return true; }
    void end() noexcept override { started_ = false; }
    [[nodiscard]] LinkKind kind() const noexcept override { return LinkKind::Uart; }
    IoStatus exchange(const Frame& tx, Frame& rx, std::uint32_t) noexcept override {
        if (!started_ || !tx.valid()) return IoStatus::BusError;
        if (tx.bytes[0] == 0xD3) {
            rx.size = 3; rx.bytes[0] = 0x06; rx.bytes[1] = 0xD3; rx.bytes[2] = 0x01;
        } else if (tx.bytes[0] == 0x10 && tx.size >= 2 && tx.bytes[1] == 0xEE) {
            rx.size = 1; rx.bytes[0] = 0x15;
        } else if (tx.bytes[0] == 0x10 && tx.size >= 2 && tx.bytes[1] == 0xAA) {
            rx.size = 2; rx.bytes[0] = 0x7F; rx.bytes[1] = tx.bytes[1];
        } else if (tx.bytes[0] == 0x10 || tx.bytes[0] == 0x11) {
            rx.size = 2; rx.bytes[0] = 0x06; rx.bytes[1] = tx.size > 1 ? tx.bytes[1] : 0;
        } else {
            rx.size = 1; rx.bytes[0] = 0x15;
        }
        return IoStatus::Ok;
    }
private:
    bool started_{false};
};

// Normalize the fictional model's one-byte status response and ignore its
// echoed payload byte. Real protocol models should define their own stable
// response fields / masks rather than assuming all response bytes are state.
static Frame model_state_key(const Frame& response) noexcept {
    Frame key{};
    key.size = response.size > 0 ? 2U : 1U;
    key.bytes[0] = static_cast<std::uint8_t>(response.size);
    if (response.size > 0) key.bytes[1] = response.bytes[0];
    return key;
}

static std::uint32_t model_state_fingerprint(const Frame& response, ResponseKind kind) noexcept {
    std::uint32_t hash = 2166136261U;
    const auto mix = [&hash](std::uint8_t byte) {
        hash ^= byte;
        hash *= 16777619U;
    };
    mix(static_cast<std::uint8_t>(kind));
    mix(static_cast<std::uint8_t>(response.size));
    if (response.size > 0) mix(response.bytes[0]);
    return hash;
}

struct KeptSeed {
    Frame frame{};
    std::uint16_t tag{0};
    std::uint8_t immutable_prefix{1};
    std::uint8_t minimum_mutable_bytes{1};
    std::uint32_t response_fp{0}; // index/diagnostic aid; never unique identity
    Frame response_key{};
    ResponseKind kind{ResponseKind::Data};
    bool used{false};
};

static bool keep_novel(std::array<KeptSeed, kMaxCorpusEntries>& kept,
                       std::uint8_t& kept_count, const Frame& frame,
                       std::uint16_t tag, std::uint8_t immutable_prefix,
                       std::uint8_t minimum_mutable_bytes, const Frame& response,
                       ResponseKind kind) noexcept {
    const std::uint32_t fp = model_state_fingerprint(response, kind);
    for (std::uint8_t i = 0; i < kept_count; ++i) {
        if (kept[i].kind != kind || kept[i].response_fp != fp ||
            kept[i].response_key.size != response.size) continue;
        bool exact_match = true;
        for (std::uint16_t j = 0; j < response.size; ++j) {
            if (kept[i].response_key.bytes[j] != response.bytes[j]) {
                exact_match = false;
                break;
            }
        }
        if (exact_match) return false;
    }
    if (kept_count >= kept.size()) return false;
    kept[kept_count++] = KeptSeed{frame, tag, immutable_prefix,
                                  minimum_mutable_bytes, fp, response, kind, true};
    return true;
}

static bool write_optimized_header(const std::string& path,
                                   const std::array<KeptSeed, kMaxCorpusEntries>& kept,
                                   std::uint8_t count) {
    std::ofstream out(path, std::ios::trunc);
    if (!out) return false;
    out << "#pragma once\n#include \"nexus/types.hpp\"\n\n"
           "// Generated by NEXUS-HW host response-state corpus minimizer.\n"
           "// Revalidate every entry against the target protocol documentation before hardware use.\n"
           "namespace nexus::generated {\n"
           "inline SeedSet make_optimized_corpus() noexcept {\n"
           "    SeedSet set{};\n"
           "    set.count = " << static_cast<unsigned>(count) << ";\n";
    for (std::uint8_t i = 0; i < count; ++i) {
        const auto& item = kept[i];
        out << "    set.entries[" << static_cast<unsigned>(i) << "].frame.size = "
            << item.frame.size << ";\n    set.entries[" << static_cast<unsigned>(i)
            << "].frame.bytes = {";
        for (std::uint16_t j = 0; j < item.frame.size; ++j) {
            if (j) out << ", ";
            out << "0x" << std::hex << std::uppercase << std::setw(2)
                << std::setfill('0') << static_cast<unsigned>(item.frame.bytes[j]) << std::dec;
        }
        out << "};\n    set.entries[" << static_cast<unsigned>(i)
            << "].immutable_prefix = " << static_cast<unsigned>(item.immutable_prefix)
            << ";\n    set.entries[" << static_cast<unsigned>(i)
            << "].minimum_mutable_bytes = " << static_cast<unsigned>(item.minimum_mutable_bytes)
            << ";\n    set.entries[" << static_cast<unsigned>(i)
            << "].command_tag = 0x" << std::hex << std::uppercase << item.tag << std::dec << ";\n";
    }
    out << "    return set;\n}\n} // namespace nexus::generated\n";
    return static_cast<bool>(out);
}


static const char* response_name(ResponseKind kind) noexcept {
    switch (kind) {
        case ResponseKind::Ack: return "ack";
        case ResponseKind::Nack: return "nack";
        case ResponseKind::DeviceError: return "device_error";
        case ResponseKind::Timeout: return "timeout";
        case ResponseKind::Data: return "data";
        case ResponseKind::BusError: return "bus_error";
        case ResponseKind::OversizedResponse: return "oversized_response";
    }
    return "unknown";
}

static const char* mutation_name(MutationKind kind) noexcept {
    switch (kind) {
        case MutationKind::BitFlip: return "bit_flip";
        case MutationKind::Arithmetic: return "arithmetic";
        case MutationKind::InterestingByte: return "interesting_byte";
        case MutationKind::BlockFill: return "block_fill";
    }
    return "unknown";
}

static void write_hex(std::ostream& out, const Frame& frame) {
    constexpr char hex[] = "0123456789abcdef";
    for (std::uint16_t i = 0; i < frame.size; ++i) {
        out.put(hex[(frame.bytes[i] >> 4U) & 0x0FU]);
        out.put(hex[frame.bytes[i] & 0x0FU]);
    }
}

// Instrumented coverage model for the fictional host fixture. Physical target
// coverage must arrive through NXCOV1 instrumentation records; these IDs are
// never represented as coverage of a real device firmware.
static FeedbackSnapshot demo_feedback(const Frame& request, const Frame& response,
                                      ResponseKind outcome) noexcept {
    FeedbackSnapshot feedback{};
    (void)feedback.add(0); // parser entry
    if (!request.valid()) return feedback;
    if (request.bytes[0] == 0x10U) {
        (void)feedback.add(1); // command family 0x10
        const std::uint8_t value = request.size > 1U ? request.bytes[1] : 0U;
        if (value == 0xEEU) (void)feedback.add(2); // explicit NACK branch
        if (value == 0xAAU) (void)feedback.add(3); // explicit device-error branch
        if (value == 0x7FU || value == 0x80U) (void)feedback.add(4); // parser boundary
        if (request.size > 2U && request.bytes[2] != 0U) (void)feedback.add(5);
    } else if (request.bytes[0] == 0x11U) {
        (void)feedback.add(6); // command family 0x11
        if (request.size > 1U && (request.bytes[1] & 1U) != 0U) (void)feedback.add(7);
    } else if (request.bytes[0] == 0xD3U) {
        (void)feedback.add(8); // read-only status family
    } else {
        (void)feedback.add(9); // unknown command path
    }
    if (outcome == ResponseKind::Ack) (void)feedback.add(16);
    else if (outcome == ResponseKind::Nack) (void)feedback.add(17);
    else if (outcome == ResponseKind::DeviceError) (void)feedback.add(18);
    else if (outcome == ResponseKind::Timeout) (void)feedback.add(19);
    if (response.size > 1U && response.bytes[0] == 0x06U) (void)feedback.add(20);
    return feedback;
}

static int run_campaign(std::uint32_t cases, std::uint32_t seed,
                        const std::string& output_path) {
    if (cases == 0U || cases > 1'000'000U) {
        std::fprintf(stderr, "Usage: nexus_sim --campaign [1..1000000] [seed] [output.jsonl]\n");
        return 2;
    }
    const SeedSet initial = example::make_lab_corpus();
    const ProtocolProfile profile = example::make_lab_profile();
    CoverageGuidedScheduler scheduler{};
    if (!scheduler.initialize(initial)) {
        std::fprintf(stderr, "campaign: invalid initial corpus\n");
        return 2;
    }
    scheduler.set_seed(seed);
    DemoTransport target;
    if (!target.begin()) return 2;
    std::ofstream report(output_path, std::ios::trunc);
    if (!report) {
        target.end();
        std::fprintf(stderr, "campaign: cannot create report: %s\n", output_path.c_str());
        return 2;
    }

    std::uint32_t executed = 0;
    std::uint32_t novel_cases = 0;
    std::uint32_t coverage_events = 0;
    std::uint32_t response_events = 0;
    std::uint32_t case_id = 0;
    std::array<std::uint32_t, 7> outcomes{};
    Mutator mutator(seed ^ 0x9E3779B9U);

    for (; executed < cases; ++executed) {
        const CampaignSeed* selected = scheduler.select();
        if (selected == nullptr) break;
        const CorpusEntry parent = selected->corpus;
        SeedSet one{};
        one.count = 1;
        one.entries[0] = parent;
        Frame input{};
        std::uint32_t generated_id = 0;
        std::uint16_t tag = 0;
        MutationKind mutation{};
        if (!mutator.next(one, input, generated_id, tag, mutation)) break;

        Frame response{};
        const auto started = std::chrono::steady_clock::now();
        const IoStatus status = target.exchange(input, response, 20'000U);
        const auto finished = std::chrono::steady_clock::now();
        const auto latency_signed = std::chrono::duration_cast<std::chrono::microseconds>(finished - started).count();
        const std::uint32_t latency = latency_signed < 0 ? 0U : static_cast<std::uint32_t>(latency_signed);
        const ResponseKind kind = classify(response, status, profile);
        const FeedbackSnapshot feedback = demo_feedback(input, response, kind);

        CorpusEntry candidate = parent;
        candidate.frame = input;
        const CampaignObservation observation = scheduler.observe(candidate, feedback, kind, ++case_id, false);
        if (observation.admitted) ++novel_cases;
        if (observation.new_coverage) ++coverage_events;
        if (observation.new_outcome) ++response_events;
        const auto outcome_index = static_cast<std::size_t>(kind);
        if (outcome_index < outcomes.size()) ++outcomes[outcome_index];

        report << "{\"schema\":\"nexus.campaign.v1\",\"type\":\"case\",\"case_id\":"
               << case_id << ",\"parent_tag\":" << tag << ",\"mutation\":\""
               << mutation_name(mutation) << "\",\"input_hex\":\"";
        write_hex(report, input);
        report << "\",\"response_hex\":\"";
        write_hex(report, response);
        report << "\",\"response_kind\":\"" << response_name(kind)
               << "\",\"latency_us\":" << latency
               << ",\"feedback_edges\":[";
        bool first_edge = true;
        for (std::uint32_t edge = 0; edge < kCampaignMapBits; ++edge) {
            if (!feedback.contains(edge)) continue;
            if (!first_edge) report << ',';
            report << edge;
            first_edge = false;
        }
        report << "],\"novel_edges\":" << observation.novel_edges
               << ",\"new_outcome\":" << (observation.new_outcome ? "true" : "false")
               << ",\"admitted\":" << (observation.new_seed ? "true" : "false")
               << ",\"corpus_size\":" << scheduler.seed_count() << "}\n";
    }
    target.end();
    report << "{\"schema\":\"nexus.campaign.v1\",\"type\":\"summary\",\"target\":\"fictional_host_model\",\"seed\":"
           << seed << ",\"requested_cases\":" << cases << ",\"executed_cases\":" << executed
           << ",\"novel_cases\":" << novel_cases << ",\"coverage_events\":" << coverage_events
           << ",\"new_response_classes\":" << response_events
           << ",\"unique_edges\":" << scheduler.total_novel_edges()
           << ",\"corpus_size\":" << scheduler.seed_count()
           << ",\"dropped_candidates\":" << scheduler.dropped_candidates()
           << ",\"outcomes\":{\"ack\":" << outcomes[static_cast<std::size_t>(ResponseKind::Ack)]
           << ",\"nack\":" << outcomes[static_cast<std::size_t>(ResponseKind::Nack)]
           << ",\"device_error\":" << outcomes[static_cast<std::size_t>(ResponseKind::DeviceError)]
           << ",\"timeout\":" << outcomes[static_cast<std::size_t>(ResponseKind::Timeout)]
           << ",\"data\":" << outcomes[static_cast<std::size_t>(ResponseKind::Data)]
           << ",\"bus_error\":" << outcomes[static_cast<std::size_t>(ResponseKind::BusError)]
           << ",\"oversized_response\":" << outcomes[static_cast<std::size_t>(ResponseKind::OversizedResponse)]
           << "}}\n";
    report.close();
    if (!report) {
        std::fprintf(stderr, "campaign: report write failed\n");
        return 2;
    }
    std::printf("CAMPAIGN_SUMMARY cases=%lu novel=%lu edges=%lu corpus=%u report=%s\n",
                static_cast<unsigned long>(executed), static_cast<unsigned long>(novel_cases),
                static_cast<unsigned long>(scheduler.total_novel_edges()),
                static_cast<unsigned>(scheduler.seed_count()), output_path.c_str());
    std::puts("NOTE: feedback is from the fictional host fixture; it is not coverage of physical firmware.");
    return 0;
}

static int host_optimize(std::uint32_t iterations, const std::string& output_path) {
    const SeedSet initial = example::make_lab_corpus();
    const ProtocolProfile profile = example::make_lab_profile();
    DemoTransport target;
    if (!target.begin()) return 2;

    std::array<KeptSeed, kMaxCorpusEntries> kept{};
    std::uint8_t kept_count = 0;
    StateGraph states{};
    std::uint32_t tested = 0;
    std::uint32_t novel = 0;

    // Always seed the minimized corpus with the known benign initial requests.
    for (std::uint8_t i = 0; i < initial.count; ++i) {
        Frame response{};
        const auto status = target.exchange(initial.entries[i].frame, response, 20'000);
        const auto kind = classify(response, status, profile);
        if (keep_novel(kept, kept_count, initial.entries[i].frame,
                       initial.entries[i].command_tag, initial.entries[i].immutable_prefix,
                       initial.entries[i].minimum_mutable_bytes, response, kind)) {
            ++novel;
            (void)states.observe_state(model_state_key(response), kind);
        }
        ++tested;
    }

    // Deterministic boundary-value pass first. This avoids relying on chance
    // to exercise common parser edge values in the host protocol model.
    constexpr std::array<std::uint8_t, 8> boundary_values{
        0x00, 0x01, 0x7F, 0x80, 0xAA, 0xEE, 0xFE, 0xFF
    };
    std::uint32_t directed_case = 0xD0000000U;
    for (std::uint8_t seed_index = 0; seed_index < initial.count; ++seed_index) {
        const auto& seed = initial.entries[seed_index];
        for (std::uint16_t offset = seed.immutable_prefix; offset < seed.frame.size; ++offset) {
            for (const auto value : boundary_values) {
                Frame input = seed.frame;
                input.bytes[offset] = value;
                Frame response{};
                const auto status = target.exchange(input, response, 20'000);
                const auto kind = classify(response, status, profile);
                const auto fp = model_state_fingerprint(response, kind);
                const auto before = states.state_count();
                const auto state_id = states.observe_state(model_state_key(response), kind);
                const bool new_state = states.state_count() > before;
                if (keep_novel(kept, kept_count, input, seed.command_tag,
                               seed.immutable_prefix, seed.minimum_mutable_bytes,
                               response, kind)) {
                    ++novel;
                    std::printf("HOST_NOVEL case=%lu tag=%04X kind=%u state=%u mutation=BOUNDARY input=",
                                static_cast<unsigned long>(directed_case),
                                static_cast<unsigned>(seed.command_tag),
                                static_cast<unsigned>(kind), static_cast<unsigned>(state_id));
                    for (std::uint16_t j = 0; j < input.size; ++j)
                        std::printf("%02X", static_cast<unsigned>(input.bytes[j]));
                    std::printf(" response_fp=%08lX novelty=%s\n",
                                static_cast<unsigned long>(fp), new_state ? "new-state" : "new-seed-response");
                }
                ++directed_case;
                ++tested;
            }
        }
    }

    Mutator mutator(0x4E455855U); // deterministic reproducibility seed
    for (std::uint32_t i = 0; i < iterations; ++i) {
        Frame input{};
        std::uint32_t case_id = 0;
        std::uint16_t tag = 0;
        MutationKind mutation{};
        if (!mutator.next(initial, input, case_id, tag, mutation)) break;
        Frame response{};
        const auto status = target.exchange(input, response, 20'000);
        const auto kind = classify(response, status, profile);
        const auto fp = model_state_fingerprint(response, kind);
        const auto before = states.state_count();
        const auto state_id = states.observe_state(model_state_key(response), kind);
        const bool new_state = states.state_count() > before;
        const bool added = keep_novel(kept, kept_count, input, tag, 1, 1, response, kind);
        if (added) {
            ++novel;
            std::printf("HOST_NOVEL case=%lu tag=%04X kind=%u state=%u mutation=%u input=",
                        static_cast<unsigned long>(case_id), static_cast<unsigned>(tag),
                        static_cast<unsigned>(kind), static_cast<unsigned>(state_id),
                        static_cast<unsigned>(mutation));
            for (std::uint16_t j = 0; j < input.size; ++j)
                std::printf("%02X", static_cast<unsigned>(input.bytes[j]));
            std::printf(" response_fp=%08lX novelty=%s\n",
                        static_cast<unsigned long>(fp), new_state ? "new-state" : "new-seed-response");
        }
        ++tested;
    }
    target.end();

    if (!write_optimized_header(output_path, kept, kept_count)) {
        std::fprintf(stderr, "Could not write optimized corpus: %s\n", output_path.c_str());
        return 2;
    }
    std::printf("HOST_OPTIMIZE_SUMMARY tested=%lu novel_responses=%lu kept=%u states=%u\n",
                static_cast<unsigned long>(tested), static_cast<unsigned long>(novel),
                static_cast<unsigned>(kept_count), static_cast<unsigned>(states.state_count()));
    std::printf("HOST_OPTIMIZE_OUTPUT %s\n", output_path.c_str());
    std::puts("NOTE: results belong to the fictional demo protocol model; validate exported seeds before attaching real hardware.");
    return 0;
}

int main(int argc, char** argv) {
    if (argc > 1 && std::string_view(argv[1]) == "--campaign") {
        std::uint32_t cases = 5000;
        std::uint32_t seed = 0x4E455855U;
        std::string output = "nexus-campaign.jsonl";
        auto parse_u32 = [](const char* value, std::uint32_t& output_value) noexcept {
            char* end = nullptr;
            const unsigned long parsed = std::strtoul(value, &end, 0);
            if (end == value || *end != '\0' || parsed == 0UL || parsed > 1'000'000UL) return false;
            output_value = static_cast<std::uint32_t>(parsed);
            return true;
        };
        if (argc > 2 && !parse_u32(argv[2], cases)) {
            std::fprintf(stderr, "Usage: nexus_sim --campaign [1..1000000] [seed] [output.jsonl]\n");
            return 2;
        }
        if (argc > 3 && !parse_u32(argv[3], seed)) {
            std::fprintf(stderr, "campaign: seed must be an integer in [1..1000000]\n");
            return 2;
        }
        if (argc > 4) output = argv[4];
        return run_campaign(cases, seed, output);
    }
    if (argc > 1 && std::string_view(argv[1]) == "--host-optimize") {
        std::uint32_t cases = 2048;
        std::string output = "optimized_corpus.hpp";
        if (argc > 2) {
            char* end = nullptr;
            const unsigned long parsed = std::strtoul(argv[2], &end, 10);
            if (end == argv[2] || *end != '\0' || parsed == 0 || parsed > 1'000'000UL) {
                std::fprintf(stderr, "Usage: nexus_sim --host-optimize [1..1000000] [output.hpp]\n");
                return 2;
            }
            cases = static_cast<std::uint32_t>(parsed);
        }
        if (argc > 3) output = argv[3];
        return host_optimize(cases, output);
    }

    if (argc > 1 && std::string_view(argv[1]) == "--opcode-sweep-sim") {
        // Exhaustive opcode enumeration is deliberately simulation-only. It
        // cannot address UART/SPI/I2C hardware from this code path.
        DemoTransport simulated_target;
        if (!simulated_target.begin()) return 2;
        const auto profile = example::make_lab_profile();
        std::uint16_t accepted = 0;
        for (std::uint16_t opcode = 0; opcode <= 0xFFU; ++opcode) {
            Frame request{}; request.size = 1;
            request.bytes[0] = static_cast<std::uint8_t>(opcode);
            Frame response{};
            const auto status = simulated_target.exchange(request, response, 20'000);
            const auto kind = classify(response, status, profile);
            if (kind != ResponseKind::Nack && kind != ResponseKind::Timeout && kind != ResponseKind::BusError) {
                ++accepted;
                std::printf("SIM_OPCODE candidate=0x%02X disposition=%u response=",
                            static_cast<unsigned>(opcode), static_cast<unsigned>(kind));
                for (std::uint16_t i = 0; i < response.size; ++i)
                    std::printf("%02X", static_cast<unsigned>(response.bytes[i]));
                std::printf("\n");
            }
        }
        simulated_target.end();
        std::printf("SIM_OPCODE_SUMMARY tested=256 accepted=%u target=fictional-local-model\n",
                    static_cast<unsigned>(accepted));
        return 0;
    }

    auto corpus = example::make_lab_corpus();
    auto profile = example::make_lab_profile();
    EngineConfig cfg{};
    cfg.authorized_lab_target = true;
    cfg.active_fuzz_enabled = true;
    cfg.max_cases = 24;
    cfg.minimum_interval_us = 1'000; // simulator only; firmware defaults to 100 ms
    cfg.calibration_rounds = 4;
    cfg.liveness.enabled = true;
    cfg.liveness.request = corpus.entries[0].frame;
    cfg.liveness.expected_response = profile.ack;
    cfg.liveness.retries = 2;

    HostClock clock;
    DemoTransport transport;
    Engine engine(transport, clock, cfg, profile);
    if (!engine.begin() || !engine.calibrate(corpus)) {
        std::fprintf(stderr, "NEXUS-HW: failed to initialize simulator\n");
        return 2;
    }

    Mutator mutator(0x12345678U);
    for (std::uint32_t i = 0; i < cfg.max_cases; ++i) {
        Frame input{};
        std::uint32_t case_id = 0;
        std::uint16_t tag = 0;
        MutationKind kind{};
        if (!mutator.next(corpus, input, case_id, tag, kind)) break;
        const auto result = engine.execute(input, case_id, tag, kind);
        std::printf("case=%lu cmd=0x%04X state=%u->%u response=%u latency_us=%lu timing_candidate=%s\n",
                    static_cast<unsigned long>(result.case_id), result.command_tag,
                    result.state_before, result.state_after, static_cast<unsigned>(result.response_kind),
                    static_cast<unsigned long>(result.latency_us),
                    result.timing_anomaly_candidate ? "yes" : "no");
        if (result.liveness_checked || result.response_kind == ResponseKind::Timeout ||
            result.response_kind == ResponseKind::BusError) {
            std::printf("  health=%u streak=%u liveness_checked=%u crash_suspected=%u\n",
                        static_cast<unsigned>(result.target_health), static_cast<unsigned>(result.failure_streak),
                        result.liveness_checked ? 1U : 0U, result.crash_suspected ? 1U : 0U);
        }
    }
    std::printf("summary: cases=%lu states=%u edges=%u health=%u crash_suspicions=%lu link_faults=%lu dropped_states=%lu dropped_edges=%lu\n",
                static_cast<unsigned long>(engine.executed_cases()), engine.graph().state_count(),
                engine.graph().edge_count(), static_cast<unsigned>(engine.target_health()),
                static_cast<unsigned long>(engine.crash_suspicions()),
                static_cast<unsigned long>(engine.link_faults()),
                static_cast<unsigned long>(engine.graph().dropped_states()),
                static_cast<unsigned long>(engine.graph().dropped_edges()));
    engine.end();
    return 0;
}
